import { render } from '@testing-library/react';
import { describe, expect, it } from 'vitest';
import FormulaBlock from '../../src/components/lesson/FormulaBlock';

describe('FormulaBlock security', () => {
  it('renders formula markup as text unless it is generated by the formula formatter', () => {
    render(
      <FormulaBlock
        expression="E_{<img src=x onerror=alert(1)>} + H^{<script>alert(1)</script>}"
        variables={[
          {
            symbol: 'X_<img src=x onerror=alert(1)>',
            description: 'test variable',
            unit: '',
          },
        ]}
      />,
    );

    expect(document.body.querySelector('img')).toBeNull();
    expect(document.body.querySelector('script')).toBeNull();
    expect(document.body.innerHTML).toContain('&lt;img src=x onerror=alert(1)&gt;');
    expect(document.body.innerHTML).toContain('&lt;script&gt;alert(1)&lt;/script&gt;');
    expect(document.body.innerHTML).toContain('<sub>');
    expect(document.body.innerHTML).toContain('<sup>');
  });
});
